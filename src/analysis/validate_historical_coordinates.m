function validate_historical_coordinates(canonical,historical,p)
%VALIDATE_HISTORICAL_COORDINATES Verify lossless boundary-side metadata.
% Historical coordinates may equal L; canonical geometry must be in [0,L).
assert(istable(canonical) && istable(historical) && ...
    isequal(canonical.ID,historical.ID) && ...
    isequal(canonical.radius,historical.radius), ...
    'VGPP:HistoricalCoordinates','Particle identities or radii differ.');
x=historical.x;y=historical.y;
assert(all(isfinite(x) & x>=0 & x<=p.Lx) && ...
    all(isfinite(y) & y>=0 & y<=p.Ly), ...
    'VGPP:HistoricalCoordinates','Invalid historical coordinates.');
x(x==p.Lx)=0;y(y==p.Ly)=0;
assert(isequal(x,canonical.x) && isequal(y,canonical.y), ...
    'VGPP:HistoricalCoordinates','Historical and canonical positions differ.');
end
